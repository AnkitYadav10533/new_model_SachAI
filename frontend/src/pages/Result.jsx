import React from 'react';
import { ResultCard } from '../components/ResultCard/ResultCard.jsx';
import { ExplanationBox } from '../components/ExplanationBox/ExplanationBox.jsx';
import { MediaViewer } from '../components/MediaViewer/MediaViewer.jsx';
import { RotateCcw, Download } from 'lucide-react';
import './Result.css';

export function Result({ result, previewUrl, textContent, onAnalyzeAnother }) {
  if (!result) return null;

  const handleExportJSON = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(result, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `SACHAI_Report_${result.fileName || 'Analysis'}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  return (
    <div className="result-page-container">
      <div className="result-page-header">
        <h2 className="page-title">
          Authenticity <span className="gradient-text">Verification Report</span>
        </h2>
        <p className="page-subtitle">
          Comprehensive forensic breakdown generated by SACHAI Engine.
        </p>
      </div>

      <div className="result-actions-top">
        <button className="btn-secondary" onClick={onAnalyzeAnother}>
          <RotateCcw size={16} />
          Analyze Another File
        </button>
        <button className="btn-secondary" onClick={handleExportJSON}>
          <Download size={16} />
          Export Report JSON
        </button>
      </div>

      {/* Main Result Badge & Confidence Meter */}
      <ResultCard result={result} />

      {/* Media Viewer Component */}
      <MediaViewer
        previewUrl={previewUrl}
        mediaType={result.mediaType}
        textContent={textContent}
        fileName={result.fileName}
      />

      {/* Technical Signals & Explanations */}
      <ExplanationBox
        technicalSignals={result.technicalSignals}
        explanations={result.explanations}
      />
    </div>
  );
}
